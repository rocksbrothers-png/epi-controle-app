#!/usr/bin/env python3
"""Mirror regional catalogues to avoid Portuguese gen-l10n fallback in base languages."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ARB_DIR = Path(__file__).resolve().parents[1] / 'packages/epi_i18n/lib/l10n'
ALIASES = {'pt': 'pt_BR', 'en': 'en_US', 'es': 'es_ES', 'fr': 'fr_FR', 'no': 'no_NO'}


def expected_alias(alias: str, regional: str) -> dict:
    source = json.loads((ARB_DIR / f'app_{regional}.arb').read_text(encoding='utf-8'))
    source['@@locale'] = alias
    source['@@comment'] = f'Base-language mirror of {regional}; generated by tool/sync_locale_aliases.py.'
    return source


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Update the five base-language ARBs')
    args = parser.parse_args()
    drift = []
    for alias, regional in ALIASES.items():
        path = ARB_DIR / f'app_{alias}.arb'
        expected = expected_alias(alias, regional)
        if args.write:
            path.write_text(json.dumps(expected, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        elif json.loads(path.read_text(encoding='utf-8')) != expected:
            drift.append(path.name)
    if drift:
        print('Base-language catalogue drift: ' + ', '.join(drift))
        print('Run python3 tool/sync_locale_aliases.py --write after updating regional catalogues.')
        return 1
    print('Five base-language catalogues match their regional translations.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
