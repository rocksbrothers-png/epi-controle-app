void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  const pairs = {'pt': 'BR', 'en': 'US', 'es': 'ES', 'fr': 'FR', 'no': 'NO'};
  for (final pair in pairs.entries) {
    test(
      'generated base ${pair.key} matches regional ${pair.value} for every message',
      () async {
        final base = await AppLocalizations.delegate.load(Locale(pair.key));
        final regional = await AppLocalizations.delegate.load(
          Locale(pair.key, pair.value),
        );
        final baseMessages = messages(base),
            regionalMessages = messages(regional);
        final catalogue =
            jsonDecode(
                  File(
                    '../../packages/epi_i18n/lib/l10n/app_pt_BR.arb',
                  ).readAsStringSync(),
                )
                as Map<String, dynamic>;
        expect(
          baseMessages.keys.toSet(),
          catalogue.keys.where((key) => !key.startsWith('@')).toSet(),
        );
        expect(baseMessages, regionalMessages);
        expect(base.epiCaLabel, contains('CA'));
        expect(base.employeeCpfLabel, contains('CPF'));
      },
    );
  }
}
