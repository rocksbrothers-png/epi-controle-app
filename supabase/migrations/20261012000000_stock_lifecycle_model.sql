CREATE TABLE IF NOT EXISTS epi_stock_decisions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    unit_id INTEGER NOT NULL,
    epi_id INTEGER NOT NULL,
    stock_item_id INTEGER NOT NULL,
    action TEXT NOT NULL CHECK (action IN ('unblock', 'return_base', 'quarantine', 'supplier_return', 'discard')),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    justification TEXT NOT NULL CHECK (length(btrim(justification)) > 0),
    reason_code TEXT NOT NULL CHECK (length(btrim(reason_code)) > 0),
    requested_by_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_by_user_id INTEGER REFERENCES users(id) ON DELETE RESTRICT,
    decided_at TIMESTAMPTZ,
    decision_justification TEXT,
    row_version BIGINT NOT NULL DEFAULT 0 CHECK (row_version >= 0),
    UNIQUE (company_id, epi_id, stock_item_id, id),
    FOREIGN KEY (company_id, unit_id) REFERENCES units(company_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (company_id, epi_id, stock_item_id) REFERENCES epi_stock_items(company_id, epi_id, id) ON DELETE RESTRICT,
    CHECK ((status = 'pending' AND decided_by_user_id IS NULL AND decided_at IS NULL) OR
           (status <> 'pending' AND decided_by_user_id IS NOT NULL AND decided_at IS NOT NULL
            AND decided_at >= requested_at AND COALESCE(length(btrim(decision_justification)), 0) > 0))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_stock_decision_pending
    ON epi_stock_decisions(company_id, stock_item_id) WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS epi_stock_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    epi_id INTEGER NOT NULL,
    stock_item_id INTEGER NOT NULL,
    lot_id INTEGER,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    event_type TEXT NOT NULL CHECK (event_type IN (
        'receipt', 'block', 'unblock', 'transfer', 'delivery', 'return',
        'return_base', 'quarantine', 'discard', 'supplier_return',
        'expiry_regularization', 'reserve', 'reservation_release', 'reconcile',
        'disposition_requested', 'disposition_rejected')),
    origin_unit_id INTEGER,
    destination_unit_id INTEGER,
    reason_code TEXT NOT NULL CHECK (length(btrim(reason_code)) > 0),
    justification TEXT NOT NULL CHECK (length(btrim(justification)) > 0),
    actor_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    actor_name_snapshot TEXT NOT NULL,
    actor_role_snapshot TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    before_values JSONB NOT NULL DEFAULT '{}',
    after_values JSONB NOT NULL DEFAULT '{}',
    decision_id INTEGER,
    stock_movement_id INTEGER,
    FOREIGN KEY (company_id, epi_id, stock_item_id, decision_id) REFERENCES epi_stock_decisions(company_id, epi_id, stock_item_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (company_id, epi_id, stock_movement_id) REFERENCES stock_movements(company_id, epi_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (company_id, epi_id, stock_item_id) REFERENCES epi_stock_items(company_id, epi_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (company_id, epi_id, lot_id) REFERENCES epi_stock_lots(company_id, epi_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (company_id, origin_unit_id) REFERENCES units(company_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (company_id, destination_unit_id) REFERENCES units(company_id, id) ON DELETE RESTRICT,
    CHECK (origin_unit_id IS NOT NULL OR destination_unit_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_stock_events_history ON epi_stock_events(company_id, stock_item_id, created_at, id);

CREATE OR REPLACE FUNCTION reject_stock_event_mutation() RETURNS TRIGGER
LANGUAGE plpgsql AS $$ BEGIN
    RAISE EXCEPTION 'Histórico de estoque é imutável' USING ERRCODE = '23514';
END $$;
DROP TRIGGER IF EXISTS stock_events_immutable ON epi_stock_events;
CREATE TRIGGER stock_events_immutable BEFORE UPDATE OR DELETE ON epi_stock_events
    FOR EACH ROW EXECUTE FUNCTION reject_stock_event_mutation();

-- Valida o responsável na escrita, preservando snapshots históricos mesmo
-- se o usuário mudar de nome/role/empresa posteriormente.
CREATE OR REPLACE FUNCTION stock_actor_company_guard() RETURNS TRIGGER
LANGUAGE plpgsql AS $$ DECLARE field_name TEXT; actor_id INTEGER; actor_company INTEGER; BEGIN
    FOREACH field_name IN ARRAY TG_ARGV LOOP
        IF TG_OP = 'UPDATE' AND NEW.company_id = OLD.company_id AND
           (to_jsonb(NEW) -> field_name) IS NOT DISTINCT FROM (to_jsonb(OLD) -> field_name) THEN
            CONTINUE;
        END IF;
        actor_id := (to_jsonb(NEW) ->> field_name)::INTEGER;
        IF actor_id IS NULL THEN CONTINUE; END IF;
        SELECT company_id INTO actor_company FROM users WHERE id = actor_id;
        IF actor_company IS DISTINCT FROM NEW.company_id THEN
            RAISE EXCEPTION 'Responsável fora da empresa do registro de estoque' USING ERRCODE = '23514';
        END IF;
    END LOOP;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS stock_lot_actor_scope ON epi_stock_lots;
CREATE TRIGGER stock_lot_actor_scope BEFORE INSERT OR UPDATE ON epi_stock_lots
    FOR EACH ROW EXECUTE FUNCTION stock_actor_company_guard('received_by_user_id');
DROP TRIGGER IF EXISTS stock_config_actor_scope ON company_stock_validity_config;
CREATE TRIGGER stock_config_actor_scope BEFORE INSERT OR UPDATE ON company_stock_validity_config
    FOR EACH ROW EXECUTE FUNCTION stock_actor_company_guard('updated_by_user_id');
DROP TRIGGER IF EXISTS stock_decision_actor_scope ON epi_stock_decisions;
CREATE TRIGGER stock_decision_actor_scope BEFORE INSERT OR UPDATE ON epi_stock_decisions
    FOR EACH ROW EXECUTE FUNCTION stock_actor_company_guard('requested_by_user_id', 'decided_by_user_id');
DROP TRIGGER IF EXISTS stock_event_actor_scope ON epi_stock_events;
CREATE TRIGGER stock_event_actor_scope BEFORE INSERT ON epi_stock_events
    FOR EACH ROW EXECUTE FUNCTION stock_actor_company_guard('actor_user_id');

