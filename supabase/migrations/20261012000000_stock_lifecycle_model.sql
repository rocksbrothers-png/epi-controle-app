CREATE TABLE IF NOT EXISTS epi_stock_lots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    epi_id INTEGER NOT NULL,
    receipt_unit_id INTEGER NOT NULL,
    receipt_key TEXT NOT NULL CHECK (length(btrim(receipt_key)) > 0),
    receipt_source TEXT NOT NULL CHECK (receipt_source IN ('manual', 'purchase_request', 'purchase_order', 'regularization')),
    receipt_source_id INTEGER,
    lot_code TEXT,
    manufacture_date DATE,
    physical_expiry_date DATE,
    manufacturer_life_value INTEGER CHECK (manufacturer_life_value > 0),
    manufacturer_life_unit TEXT,
    expiry_source TEXT NOT NULL DEFAULT 'unknown'
        CHECK (expiry_source IN ('unknown', 'label', 'manufacturer_document', 'regularization')),
    expiry_evidence TEXT,
    ca_snapshot TEXT,
    ca_expiry_snapshot DATE,
    received_quantity INTEGER NOT NULL CHECK (received_quantity > 0),
    supplier_id INTEGER,
    supplier_name_snapshot TEXT,
    -- PostgreSQL ordena NaN acima de números: apenas >= 0 não o rejeita.
    unit_cost NUMERIC(18,4) CHECK (unit_cost BETWEEN 0 AND 99999999999999.9999),
    currency TEXT NOT NULL DEFAULT 'BRL' CHECK (currency = 'BRL'),
    received_by_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (company_id, receipt_key),
    UNIQUE (company_id, epi_id, id),
    FOREIGN KEY (company_id, epi_id) REFERENCES epis(company_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (company_id, receipt_unit_id) REFERENCES units(company_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (company_id, supplier_id) REFERENCES authorized_suppliers(company_id, id) ON DELETE RESTRICT,
    CHECK (manufacture_date IS NULL OR physical_expiry_date IS NULL OR physical_expiry_date >= manufacture_date),
    CHECK ((manufacturer_life_value IS NULL AND manufacturer_life_unit IS NULL) OR
           (COALESCE(manufacturer_life_value, 0) > 0 AND COALESCE(manufacturer_life_unit, '') IN ('days', 'months', 'years'))),
    CHECK ((physical_expiry_date IS NULL AND expiry_source = 'unknown') OR
           (physical_expiry_date IS NOT NULL AND expiry_source <> 'unknown' AND COALESCE(length(btrim(expiry_evidence)), 0) > 0))
);

