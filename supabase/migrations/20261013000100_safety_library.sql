CREATE OR REPLACE FUNCTION safety_history_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Immutable document history'; END $$;
CREATE OR REPLACE FUNCTION safety_version_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' OR (to_jsonb(NEW)-'state') IS DISTINCT FROM (to_jsonb(OLD)-'state') THEN
  RAISE EXCEPTION 'Immutable document version';
 END IF;
 IF NEW.state<>OLD.state AND NOT (
  (OLD.state='draft' AND NEW.state IN ('published','archived')) OR
  (OLD.state='published' AND NEW.state IN ('superseded','archived')) OR
  (OLD.state='superseded' AND NEW.state='archived')
 ) THEN RAISE EXCEPTION 'Invalid document state transition'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS safety_version_guard ON safety_document_versions;
CREATE TRIGGER safety_version_guard BEFORE UPDATE OR DELETE ON safety_document_versions
 FOR EACH ROW EXECUTE FUNCTION safety_version_immutable();
