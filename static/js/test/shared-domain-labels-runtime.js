function load() {
  const ctx = vm.createContext({});
  ctx.globalThis = ctx;
  vm.runInContext(fs.readFileSync(path.join(JS_ROOT, MODULE), 'utf8'), ctx);
  return ctx;
}

module.exports = function ({ test, assert, eq }) {
  test('UBX-V3 domain-labels: publica os 7 nomes legados e o namespace congelado', () => {
    const ctx = load();
    for (const name of NAMES) { eq(typeof ctx[name], 'function', name); }
    const ns = ctx.__EPI_SHARED_DOMAIN_LABELS__;
    assert(Object.isFrozen(ns), 'namespace congelado');
    eq(Object.keys(ns).sort().join(','), [...NAMES].sort().join(','));
  });

  for (const key of Object.keys(EXPECTED)) {
    test(`UBX-V3 domain-labels: ${key} reproduz o app.js original`, () => {
      const ctx = load();
      const actual = scenario(ctx, (fn) => { ctx.tr = fn; })[key];
      eq(JSON.stringify(actual), JSON.stringify(EXPECTED[key]), key);
    });
  }

  test('UBX-V3 domain-labels: o tradutor é lido na chamada (troca depois do boot vale)', () => {
    const ctx = load();
    ctx.tr = () => 'primeiro';
    eq(ctx.unitTypeLabel('navio'), 'primeiro');
    ctx.tr = () => 'trocado';
    eq(ctx.unitTypeLabel('navio'), 'trocado');
    delete ctx.tr;
    eq(ctx.unitTypeLabel('navio'), 'Embarcação', 'sem app.js (teste isolado) usa o texto padrão');
  });

  test('UBX-V3 domain-labels: carrega antes do app.js e das views que leem os rótulos', () => {
    const scripts = fs.readFileSync(path.resolve(JS_ROOT, '..', 'views', '_scripts.html'), 'utf8');
    const order = [...scripts.matchAll(/<script[^>]+src="([^"?]+)/g)].map((m) => m[1]);
    const mod = order.indexOf(`/js/${MODULE}`);
    assert(mod >= 0, 'módulo listado em _scripts.html');
    assert(mod < order.indexOf('/app.js'), 'antes do app.js');
    assert(mod < order.indexOf('/js/views/estoque.js'), 'antes de views/estoque.js');
    const app = fs.readFileSync(path.resolve(JS_ROOT, '..', 'app.js'), 'utf8');
    for (const name of NAMES) {
      assert(!new RegExp(`^(?:async\\s+)?function\\s+${name}\\(`, 'm').test(app), `${name} voltou ao app.js`);
    }
  });
};

