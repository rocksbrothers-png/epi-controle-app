function readLocale(locale) {
  return JSON.parse(fs.readFileSync(path.resolve(JS_ROOT, '..', 'i18n', `${locale}.json`), 'utf8'));
}

// Mesmo contrato do trEpi (static/i18n.js): chave aninhada; sem tradução,
// devolve o fallback.
function dictionaryTranslator(dict) {
  return (key, fallback) => {
    let val = dict;
    for (const part of String(key).split('.')) { val = val && typeof val === 'object' ? val[part] : undefined; }
    return (typeof val === 'string' && val && val !== key) ? val : (fallback !== undefined ? fallback : key);
  };
}

